"""Export the headline experiment results for the replay app's results scorecard.

Reads results/baseline/metrics.json and results/countermeasure/metrics.json (already
generated by run_baseline.py and run_countermeasure.py) and writes a small summary the
app can show next to the live replay:

  baseline    clean-data accuracy of each model on chronological test folds
  grid        the 4 conditions x with/without fix (windows 3-7, 5-seed means)
  overTime    the combined condition's error and P90 coverage per simulated window
  unseen      defects the fix was not designed around, plus the no-check-flight failure

Nothing is recomputed here; every number is copied (and rounded) from the metrics files.

Writes web/public/data/results.json.

Usage: python3 scripts/export_web_results.py [results_dir] [web_data_dir]
"""

import json
import sys
from pathlib import Path

RESULTS = Path(sys.argv[1] if len(sys.argv) > 1 else "results")
WEB_DATA = Path(sys.argv[2] if len(sys.argv) > 2 else "web/public/data")

CONDITIONS = {"reference": "Clean", "stale": "Stale", "low_quality": "Low quality", "combined": "Both"}
UNSEEN = {
    "unseen_bias_20pct": "Damaged sensors read 20% low",
    "unseen_drifting_bias": "Bias drifts each window",
    "unseen_offset": "Fixed 2.5 A offset",
    "unseen_overreading": "Damaged sensors read 10% high",
}
FAILURE = ("failure_no_reference_flights", "No check flights")


def r(x, n=2):
    return round(float(x), n)


def cell(m: dict) -> dict:
    """One condition x fix cell: accuracy, safety margin and the decisions it leads to."""
    mean = lambda k: m[k]["mean"]  # noqa: E731
    return {
        "maeWh": r(mean("mae_wh")),
        "biasWh": r(mean("bias_wh")),
        "p90": r(mean("p90_coverage"), 3),
        "unsafe": r(mean("unsafe_all"), 1),
        "aborts": r(mean("abort_all"), 1),
        "deferred": r(mean("deferred_all"), 1),
    }


def main():
    base = json.loads((RESULTS / "baseline" / "metrics.json").read_text())
    cm = json.loads((RESULTS / "countermeasure" / "metrics.json").read_text())
    grid_src = cm["main_grid_after_outage"]
    unseen_src = cm["unseen_and_failure_after_outage"]
    any_cell = grid_src["reference/no_fix"]

    models = {}
    for name in ("physics_only", "direct_ml", "hybrid"):
        p = base["results"][name]["pooled_test_seed_mean"]
        models[name] = {"maeWh": r(p["mae_wh"]), "p90": r(p["p90_coverage"], 3)}

    by_window = cm["by_window_seed_mean"]
    windows = sorted({int(k.rsplit("/", 1)[1]) for k in by_window if k.startswith("combined/")})
    over_time = {
        "windows": windows,
        **{
            f"{metric}{'On' if fix == 'fix' else 'Off'}": [r(by_window[f"combined/{fix}/{w}"][key], 3) for w in windows]
            for fix in ("no_fix", "fix")
            for metric, key in (("mae", "mae_wh"), ("p90", "p90_coverage"))
        },
    }

    out = {
        "simulated": "Degradation results use a SIMULATED timeline built from the 196 CMU flights; see results/degradation and results/countermeasure.",
        "baseline": {
            "flights": base["data"]["flights"],
            "checkpoints": base["data"]["checkpoints"],
            "split": "chronological folds, whole flights kept together",
            "models": models,
        },
        "windows": cm["after_outage_windows"],
        "seeds": len(cm["settings"]["seeds"]),
        "decisions": {"total": int(any_cell["positives_all"]["mean"] + any_cell["negatives_all"]["mean"]),
                      "shouldReturn": int(any_cell["positives_all"]["mean"])},
        "grid": [
            {"key": k, "label": label, "off": cell(grid_src[f"{k}/no_fix"]), "on": cell(grid_src[f"{k}/fix"])}
            for k, label in CONDITIONS.items()
        ],
        "overTime": over_time,
        "unseen": [
            {"key": k, "label": label, "off": cell(unseen_src[f"{k}/no_fix"]), "on": cell(unseen_src[f"{k}/fix"])}
            for k, label in UNSEEN.items()
        ],
        "failure": {"key": FAILURE[0], "label": FAILURE[1],
                    "off": cell(unseen_src[f"{FAILURE[0]}/no_fix"]), "on": cell(unseen_src[f"{FAILURE[0]}/fix"])},
        # Reference flights are presented as check flights flown with a known-good backup sensor.
        "cost": cm["countermeasure"]["cost"].replace("dual-logged reference flights", "check flights with a known-good backup sensor"),
    }
    path = WEB_DATA / "results.json"
    path.write_text(json.dumps(out, indent=1) + "\n")
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
